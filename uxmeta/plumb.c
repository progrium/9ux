/*
 * Plumbing rules generated from the merged associations; see meta.md §5.
 */
#include <u.h>
#include <libc.h>
#include <ctype.h>
#include "meta.h"

typedef struct Assoc Assoc;
struct Assoc {
	Ent	*ext;
	Rec	*r;	/* resolved */
};

static int
assoccmp(void *a, void *b)
{
	Assoc *x, *y;
	int lx, ly;

	x = a;
	y = b;
	lx = strlen(x->ext->key);
	ly = strlen(y->ext->key);
	if(lx != ly)
		return ly - lx;
	return strcmp(x->ext->key, y->ext->key);
}

/* a regexp(6) matching the suffix, ignoring ASCII case, in plumb quotes */
static void
suffixre(Fmt *f, char *s)
{
	Rune r;
	int n;

	for(; *s; s += n){
		n = chartorune(&r, s);
		if(r < 0x80 && isalpha(r))
			fmtprint(f, "[%c%c]", tolower(r), toupper(r));
		else if(r == '\'')
			fmtprint(f, "''");
		else if(r < 0x80 && strchr(".+*?[]()^$|\\", r) != nil)
			fmtprint(f, "\\%c", r);
		else
			fmtprint(f, "%.*s", n, s);
	}
}

static char*
plumbquote(char *s)
{
	return smprint("%q", s);
}

char*
plumbrules(Meta *m)
{
	Ent **a;
	Assoc *as;
	int i, n, na;
	Fmt f;
	Rec *r;
	char *open, *port, *exec, *type, *p, *q;

	a = viewsorted(m->v, &n);
	as = emalloc((n+1)*sizeof as[0]);
	na = 0;
	for(i = 0; i < n; i++){
		if(strcmp(a[i]->kind, "ext") != 0 || a[i]->key[0] == 0)
			continue;
		if((p = recget(a[i]->r, "plumb")) != nil && strcmp(p, "no") == 0)
			continue;
		p = smprint("/x/%s", a[i]->key);	/* something that has the suffix */
		r = metaresolve(m, p);
		free(p);
		if(recget(r, "open") == nil){
			recfree(r);
			continue;
		}
		as[na].ext = a[i];
		as[na].r = r;
		na++;
	}
	free(a);
	qsort(as, na, sizeof as[0], assoccmp);

	fmtstrinit(&f);
	fmtprint(&f, "# generated by uxmeta from ext, type and app records; don't edit.\n");
	fmtprint(&f, "# include this file in $home/lib/plumbing before 'include basic'.\n");
	for(i = 0; i < na; i++){
		r = as[i].r;
		open = recget(r, "open");
		port = recget(r, "port");
		exec = recget(r, "exec");
		type = recget(r, "type");
		fmtprint(&f, "\n# ext %s", as[i].ext->key);
		if(type)
			fmtprint(&f, ": type %s,", type);
		else
			fmtprint(&f, ":");
		fmtprint(&f, " open %s\n", open);
		fmtprint(&f, "type is text\n");
		fmtprint(&f, "data matches '.+");
		suffixre(&f, as[i].ext->key);
		fmtprint(&f, "'\n");
		fmtprint(&f, "arg isfile $0\n");
		if(port != nil && *port){
			q = plumbquote(port);
			fmtprint(&f, "plumb to %s\n", q);
			free(q);
			if(exec != nil && *exec)
				fmtprint(&f, "plumb client %s\n", exec);
		}else if(exec != nil && *exec)
			fmtprint(&f, "plumb start %s $file\n", exec);
		recfree(r);
	}
	free(as);
	return fmtstrflush(&f);
}

/* regenerate the rules file if its contents would change */
int
metaplumb(Meta *m)
{
	char *rules, *s;
	int fd, n;

	if(m->plumbfile == nil)
		return 0;
	rules = plumbrules(m);
	if(m->rules != nil && strcmp(rules, m->rules) == 0){
		free(rules);
		return 0;
	}
	if(atomicwrite(m->plumbfile, rules) < 0){
		free(rules);
		return -1;
	}
	free(m->rules);
	m->rules = rules;
	if(m->reloadplumb && m->userplumbing != nil
	&& (s = readfile(m->userplumbing, &n)) != nil){
		if((fd = open(m->plumbrulesfile ? m->plumbrulesfile : "/mnt/plumb/rules", OWRITE|OTRUNC)) >= 0){
			write(fd, s, n);
			close(fd);
		}
		free(s);
	}
	return 1;
}
