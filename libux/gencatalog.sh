#!/bin/sh
# Write tcatalog.c, the descriptors libux embeds, from uitree's
# core/types: every type of the profiles named, as their specs say,
# plus each type named +TYPE (components that have no profile yet).
# A type in LOCALDIR (libux/types: 9ux's extensions of the spec, to go
# back upstream) replaces uitree's, or adds one it doesn't have.
#
#	gencatalog.sh UITREE_TYPES_DIR LOCALDIR PROFILE... [+TYPE...] >tcatalog.c
set -eu
dir=$1
local=$2
shift 2
echo '/* Generated by gencatalog.sh from uitree core/types and libux/types; do not edit. */'
echo '#include <u.h>'
echo '#include <libc.h>'
echo
echo 'char *profiles[] = {'
for p; do case $p in +*) ;; *) echo "	\"$p\","; esac; done
echo '	nil,'
echo '};'
echo
echo 'char *catalog[] = {'
for t in $( (ls "$dir"; ls "$local") | sort -u); do
	if [ -f "$local/$t/spec" ]; then spec=$local/$t/spec
	elif [ -f "$dir/$t/spec" ]; then spec=$dir/$t/spec
	else continue; fi
	p=$(sed -n 's/^type[ 	].*profile=\([a-z-]*\).*/\1/p' "$spec")
	want=0
	for q; do [ "$q" = "$p" -o "$q" = "+$t" ] && want=1; done
	[ $want = 1 ] || continue
	echo "	\"$t\","
	sed 's/\\/\\\\/g; s/"/\\"/g; s/^/	"/; s/$/\\n"/' "$spec"
	echo '	,'
done
echo '	nil,'
echo '};'
