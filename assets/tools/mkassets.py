#!/usr/bin/env python3
"""Build 9/UX assets from their text sources into assets/gen/.

usage: mkassets.py [-check]

Writes:
    gen/icons/NAME.SIZE.img       a8r8g8b8 image(6), colour, alpha mask
    gen/icons/NAME.SIZE.1.img     a8r8g8b8 image(6), the 1-bit form
    gen/patterns/NAME.img         r8g8b8 image(6), one 8x8 tile
    gen/uxstyle.h                 colours and metrics for rio and libux
    gen/uxcursors.c               Plan 9 Cursor structs
    gen/uxglyphs.c                chrome glyph bitmaps

-check builds into a temporary directory and fails if gen/ differs, so
CI can catch sources changed without rebuilding.
"""

import filecmp
import os
import re
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(__file__))
from uxassets import (ASSETS, load_palette, load_metrics, load_icons,
                      load_cursors, load_patterns, load_glyphs,
                      write_image6_argb, write_image6_rgb)

HEADER = "/* generated by assets/tools/mkassets.py from assets/; do not edit */\n"


def cname(s):
    return re.sub(r"[^A-Za-z0-9]", "", s)


def icon_pixels(grid, bychar, mono):
    px = []
    for y in range(grid.h):
        for x in range(grid.w):
            ch = grid.at(x, y)
            if ch == ".":
                px.append((0, 0, 0, 0))
            elif mono:
                v = 255 if bychar[ch].mono(x, y) else 0
                px.append((v, v, v, 255))
            else:
                r, g, b = bychar[ch].rgb
                px.append((r, g, b, 255))
    return px


def bits(grid, want):
    """Rows of a grid as MSB-first bytes, 1 where the letter is in want."""
    out = []
    for y in range(grid.h):
        row = 0
        nb = (grid.w + 7) // 8
        for x in range(nb * 8):
            row <<= 1
            if x < grid.w and grid.at(x, y) in want:
                row |= 1
        out.extend((row >> (8 * (nb - 1 - i))) & 255 for i in range(nb))
    return out


def hexbytes(bs, per=8, indent="\t"):
    lines = []
    for i in range(0, len(bs), per):
        lines.append(indent + ", ".join("0x%02x" % b for b in bs[i:i + per]) + ",")
    return "\n".join(lines)


def build(out):
    byname, bychar = load_palette()
    os.makedirs(os.path.join(out, "icons"), exist_ok=True)
    os.makedirs(os.path.join(out, "patterns"), exist_ok=True)

    for ic in load_icons():
        for size, g in sorted(ic.sizes.items()):
            for mono, suf in ((False, ""), (True, ".1")):
                write_image6_argb(os.path.join(out, "icons", "%s.%d%s.img" % (ic.name, size, suf)),
                                  g.w, g.h, icon_pixels(g, bychar, mono))

    for p in load_patterns():
        px = [bychar[p.grid.at(x, y)].rgb for y in range(p.grid.h) for x in range(p.grid.w)]
        write_image6_rgb(os.path.join(out, "patterns", p.name + ".img"),
                         p.grid.w, p.grid.h, px)

    # uxstyle.h
    h = [HEADER, "/* colours: pass to allocimage(display, r, RGB24, 1, UXname) */", "enum {"]
    for c in byname.values():
        r, g, b = c.rgb
        h.append("\tUX%s\t= 0x%02X%02X%02XFF," % (c.name, r, g, b))
    h.append("};\n")
    h.append("/* metrics in pixels at 1x: see assets/metrics.ndb */")
    h.append("enum {")
    for k, v in load_metrics().items():
        h.append("\tUX%s\t= %d," % (cname(k), v))
    h.append("};\n")
    with open(os.path.join(out, "uxstyle.h"), "w") as f:
        f.write("\n".join(h))

    # uxcursors.c: Cursor{offset, clr, set}; set bits draw black and
    # clr bits white, as in cursor(2).
    c = [HEADER, "#include <u.h>", "#include <libc.h>", "#include <draw.h>",
         "#include <cursor.h>", ""]
    for cur in load_cursors():
        c.append("Cursor ux%scursor = {" % cname(cur.name))
        c.append("\t{%d, %d}," % (-cur.hot[0], -cur.hot[1]))
        c.append("\t{\n" + hexbytes(bits(cur.grid, "W"), 8, "\t\t") + "\n\t},")
        c.append("\t{\n" + hexbytes(bits(cur.grid, "K"), 8, "\t\t") + "\n\t},")
        c.append("};\n")
    with open(os.path.join(out, "uxcursors.c"), "w") as f:
        f.write("\n".join(c))

    # uxglyphs.c: k is the ink layer, w the white layer, MSB first,
    # (w+7)/8 bytes a row; load each with loadimage into a GREY1 image
    # and use it as a mask.
    gl = [HEADER, "#include <u.h>", "#include <libc.h>", "",
          "typedef struct UXglyph UXglyph;",
          "struct UXglyph {", "\tchar\t*name;", "\tint\tw, h;",
          "\tuchar\t*k;", "\tuchar\t*w;", "};", ""]
    glyphs = load_glyphs()
    for name, g in glyphs.items():
        n = cname(name)
        gl.append("static uchar %sk[] = {\n%s\n};" % (n, hexbytes(bits(g, "K"))))
        gl.append("static uchar %sw[] = {\n%s\n};" % (n, hexbytes(bits(g, "W"))))
    gl.append("\nUXglyph uxglyphs[] = {")
    for name, g in glyphs.items():
        n = cname(name)
        gl.append('\t{"%s", %d, %d, %sk, %sw},' % (name, g.w, g.h, n, n))
    gl.append("\t{nil},\n};\n")
    with open(os.path.join(out, "uxglyphs.c"), "w") as f:
        f.write("\n".join(gl))


def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    # dircmp is shallow; compare contents
    for f in cmp.common_files:
        if not filecmp.cmp(os.path.join(a, f), os.path.join(b, f), shallow=False):
            return False
    return all(same_tree(os.path.join(a, d), os.path.join(b, d)) for d in cmp.common_dirs)


def main(argv):
    gen = os.path.join(ASSETS, "gen")
    if argv[1:] == ["-check"]:
        tmp = tempfile.mkdtemp()
        try:
            build(tmp)
            if not os.path.isdir(gen) or not same_tree(tmp, gen):
                sys.exit("assets/gen is out of date: run assets/tools/mkassets.py")
        finally:
            shutil.rmtree(tmp)
        return
    if argv[1:]:
        sys.exit(__doc__)
    if os.path.isdir(gen):
        shutil.rmtree(gen)
    build(gen)


if __name__ == "__main__":
    main(sys.argv)
