# ---------------------------------------------------------------- palettes

PAL4 = [
    0xFFFFFF, 0xFCF305, 0xFF6402, 0xDD0806, 0xF20884, 0x4600A5, 0x0000D4, 0x02ABEA,
    0x1FB714, 0x006411, 0x562C05, 0x90713A, 0xC0C0C0, 0x808080, 0x404040, 0x000000,
]


def pal8():
    p = []
    for i in range(215):
        p.append(((0xFF - 0x33 * (i // 36)) << 16) | ((0xFF - 0x33 * ((i // 6) % 6)) << 8) | (0xFF - 0x33 * (i % 6)))
    ramp = [0xEE, 0xDD, 0xBB, 0xAA, 0x88, 0x77, 0x55, 0x44, 0x22, 0x11]
    p += [v << 16 for v in ramp] + [v << 8 for v in ramp] + [v for v in ramp]
    p += [(v << 16) | (v << 8) | v for v in ramp] + [0]
    assert len(p) == 256 and p[0] == 0xFFFFFF and p[35] == 0xFF0000 and p[5] == 0xFFFF00
    return p


PAL8 = pal8()

# ---------------------------------------------------------------- pixel art


def mask_art(s):
    """Opaque except the corners and a square hole in the middle."""
    m = [[1] * s for _ in range(s)]
    c = 3 if s == 32 else 2
    for y in range(s):
        for x in range(s):
            if x + y < c or (s - 1 - x) + y < c or x + (s - 1 - y) < c or (s - 1 - x) + (s - 1 - y) < c:
                m[y][x] = 0
    h = s // 8
    for y in range(s // 2 - h, s // 2 + h):
        for x in range(s // 2 - h, s // 2 + h):
            m[y][x] = 0
    return m


def bw_art(s):
    """1 = black: a border and a diagonal hatch."""
    return [[1 if x in (0, s - 1) or y in (0, s - 1) or (x + 2 * y) % 5 == 0 else 0 for x in range(s)] for y in range(s)]


def c4_art(s):
    return [[(x + y) % 16 for x in range(s)] for y in range(s)]


def c8_art(s):
    return [[(x * 7 + y * 11) % 256 for x in range(s)] for y in range(s)]


def packbits1(a):
    s = len(a)
    out = bytearray()
    for row in a:
        for i in range(0, s, 8):
            b = 0
            for k in range(8):
                b = (b << 1) | (row[i + k] & 1)
            out.append(b)
    return bytes(out)


def pack4(a):
    out = bytearray()
    for row in a:
        for i in range(0, len(row), 2):
            out.append((row[i] << 4) | row[i + 1])
    return bytes(out)


def pack8(a):
    return bytes(v for row in a for v in row)

# ---------------------------------------------------------------- image(6)


def image6(w, h, argb):
    """a8r8g8b8 image(6): 5 x 12-byte header, then B G R A per pixel."""
    hdr = b"".join(f.rjust(11).encode() + b" " for f in ["a8r8g8b8", "0", "0", str(w), str(h)])
    px = bytearray()
    for c in argb:
        if c >> 24 == 0:
            c = 0
        px += bytes([c & 0xFF, (c >> 8) & 0xFF, (c >> 16) & 0xFF, c >> 24])
    return hdr + bytes(px)


def render(art, mask, depth):
    s = len(art)
    out = []
    for y in range(s):
        for x in range(s):
            v = art[y][x]
            if depth == 1:
                c = 0x000000 if v else 0xFFFFFF
            elif depth == 4:
                c = PAL4[v]
            else:
                c = PAL8[v]
            a = 0xFF if (mask is None or mask[y][x]) else 0
            out.append((a << 24) | c)
    return image6(s, s, out)

# ---------------------------------------------------------------- resource files


def pstr(s):
    b = s.encode("mac_roman") if isinstance(s, str) else s
    assert len(b) < 256
    return bytes([len(b)]) + b


def rsrc(resources, attr=0):
    """resources: list of (type bytes, id, name or None, attr, data)."""
    data = bytearray()
    names = bytearray()
    types = []
    for t, rid, name, rattr, d in resources:
        if t not in [x[0] for x in types]:
            types.append((t, []))
        off = len(data)
        data += struct.pack(">I", len(d)) + d
        noff = 0xFFFF
        if name is not None:
            noff = len(names)
            names += pstr(name)
        for x in types:
            if x[0] == t:
                x[1].append((rid, noff, rattr, off))
    tl = bytearray(struct.pack(">H", (len(types) - 1) & 0xFFFF))
    refs = bytearray()
    reflist_start = 2 + 8 * len(types)
    for t, rs in types:
        tl += t + struct.pack(">HH", len(rs) - 1, reflist_start + len(refs))
        for rid, noff, rattr, off in rs:
            refs += struct.pack(">hHB", rid, noff, rattr) + off.to_bytes(3, "big") + b"\0\0\0\0"
    typelist = bytes(tl + refs)
    dataoff = 256
    mapoff = dataoff + len(data)
    maphdr_len = 28
    namelist_off = maphdr_len + len(typelist)
    maplen = namelist_off + len(names)
    hdr = struct.pack(">IIII", dataoff, mapoff, len(data), maplen)
    m = hdr + b"\0" * 4 + b"\0\0" + struct.pack(">HHH", attr, maphdr_len, namelist_off) + typelist + bytes(names)
    assert len(m) == maplen
    return hdr + b"\0" * (dataoff - 16) + bytes(data) + m


def menu(mid, title, items, enable=0xFFFFFFFF, proc=0):
    b = struct.pack(">hhhhhI", mid, 0, 0, proc, 0, enable) + pstr(title)
    for name, icon, key, mark, style in items:
        b += pstr(name) + bytes([icon, key, mark, style])
    return b + b"\0"


def dlog(rect, proc, vis, goaway, refcon, ditl, title, pos=None):
    t, l, b_, r = rect
    d = struct.pack(">hhhhhBBBBIh", t, l, b_, r, proc, vis, 0, goaway, 0, refcon, ditl) + pstr(title)
    if pos is not None:
        if len(d) % 2:
            d += b"\0"
        d += struct.pack(">H", pos)
    return d


def ditl(items):
    d = struct.pack(">H", (len(items) - 1) & 0xFFFF)
    for rect, typ, data in items:
        t, l, b_, r = rect
        d += b"\0\0\0\0" + struct.pack(">hhhhBB", t, l, b_, r, typ, len(data)) + data
        if len(data) % 2:
            d += b"\0"
    return d


def alrt(rect, ditl_id, stages, pos=None):
    t, l, b_, r = rect
    d = struct.pack(">hhhhhH", t, l, b_, r, ditl_id, stages)
    if pos is not None:
        d += struct.pack(">H", pos)
    return d


def curs():
    data = [[1 if x == y or x == 15 - y else 0 for x in range(16)] for y in range(16)]  # an X
    mask = [[1 if abs(x - y) <= 1 or abs(x - (15 - y)) <= 1 else 0 for x in range(16)] for y in range(16)]
    data[0][15] = 1
    mask[0][15] = 0  # one data-without-mask (invert) pixel
    data[0][14] = 1  # make sure it isn't masked either way
    raw = packbits1(data) + packbits1(mask) + struct.pack(">hh", 7, 8)  # hot spot v=7 h=8
    img = []
    for y in range(16):
        for x in range(16):
            d, m = data[y][x], mask[y][x]
            img.append(0xFF000000 if d else (0xFFFFFFFF if m else 0))
    clr = bytes(a & ~b & 0xFF for a, b in zip(packbits1(mask), packbits1(data)))
    cursor = struct.pack("<ii", -8, -7) + clr + packbits1(data)
    return raw, image6(16, 16, img), cursor


