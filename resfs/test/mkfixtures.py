"""Generate resfs test fixtures and their expected outputs.

Everything here is made from scratch: the icons are drawn by the
functions below, and no Apple resource data is used. The expected
images are computed from the same pixel art, not by decoding the
generated bytes, so they check the C decoders independently.

    python3 mkfixtures.py        # rewrites fixtures/, golden/ and cases

Output:
    fixtures/*.rsrc   resource files (good and malformed)
    golden/*          expected output of rescat for each case
    cases             one case a line: golden-name fixture rescat-args...
                      or "fail fixture rescat-args..." for an expected error
"""
