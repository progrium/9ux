def applewrap(magic, version, entries, home=None):
    """entries: (id, bytes). Data follows the entry table in order."""
    filler = home if home is not None else b"\0" * 16
    hdr = struct.pack(">II", magic, version) + filler + struct.pack(">H", len(entries))
    off = len(hdr) + 12 * len(entries)
    table = b""
    data = b""
    for eid, d in entries:
        table += struct.pack(">III", eid, off + len(data), len(d))
        data += d
    return hdr + table + data


def empty_rsrc():
    hdr = struct.pack(">IIII", 256, 256, 0, 30)
    m = hdr + b"\0" * 6 + struct.pack(">HHH", 0, 28, 30) + b"\xff\xff"
    return hdr + b"\0" * 240 + m


def amplify():
    ntypes = 8000
    tl = struct.pack(">H", ntypes - 1)
    reflist = 2 + 8 * ntypes
    for i in range(ntypes):
        tl += struct.pack(">I", 0x41410000 + i) + struct.pack(">HH", 99, reflist)
    refs = b"".join(struct.pack(">hHB", i, 0xFFFF, 0) + b"\0\0\0" + b"\0" * 4 for i in range(100))
    data = struct.pack(">I", 0)
    typelist = tl + refs
    maplen = 28 + len(typelist)
    hdr = struct.pack(">IIII", 256, 256 + len(data), len(data), maplen)
    m = hdr + b"\0" * 6 + struct.pack(">HHH", 0, 28, maplen) + typelist
    return hdr + b"\0" * 240 + data + m


